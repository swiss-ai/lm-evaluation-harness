#!/usr/bin/env python3
"""Generate the per-language and group configs for LinguaSafe.

Run from anywhere: ``python generate_configs.py``. Templates (``_linguasafe_*_yaml``)
are hand-written; this script writes ``linguasafe_<component>_<lang>.yaml``, the
``linguasafe_<component>.yaml`` groups and the ``linguasafe.yaml`` umbrella group.
"""

from pathlib import Path


LANGS = {
    "en": "English",
    "zh": "Chinese",
    "ar": "Arabic",
    "ru": "Russian",
    "sr": "Serbian",
    "th": "Thai",
    "ko": "Korean",
    "vi": "Vietnamese",
    "cs": "Czech",
    "hu": "Hungarian",
    "bn": "Bengali",
    "ms": "Malay",
}

# component -> (template, metrics aggregated in the group)
COMPONENTS = {
    "direct": ("direct", ["sw_f1", "sw_fpr", "sw_fnr", "mcq_format_error"]),
    "indirect": (
        "indirect",
        ["unsafe_rate", "harmful_rate", "sw_penalty", "judge_invalid"],
    ),
    "oversensitivity": (
        "oversensitivity",
        ["overrefusal_rate", "overrefusal_rate_judge", "judge_invalid"],
    ),
    # Extensions (not in the paper, not in the default `linguasafe` group): every prompt
    # of the given levels as open-ended generation, ignoring the MCQ split.
    "indirect_all": (
        "indirect",
        ["unsafe_rate", "harmful_rate", "sw_penalty", "judge_invalid"],
    ),
    "oversensitivity_all": (
        "oversensitivity",
        ["overrefusal_rate", "overrefusal_rate_judge", "judge_invalid"],
    ),
}
DEFAULT_GROUP = ["direct", "indirect", "oversensitivity"]

HEADER = "# Generated by generate_configs.py; do not edit by hand.\n"


def main():
    here = Path(__file__).parent
    for comp, (template, metrics) in COMPONENTS.items():
        for lang in LANGS:
            (here / f"linguasafe_{comp}_{lang}.yaml").write_text(
                HEADER
                + f"task: linguasafe_{comp}_{lang}\n"
                + f"include: _linguasafe_{template}_yaml\n"
                + f"process_docs: !function utils.process_docs_{comp}_{lang}\n",
                encoding="utf-8",
            )
        tasks = "\n".join(f"  - linguasafe_{comp}_{lang}" for lang in LANGS)
        aggs = "\n".join(
            f"  - metric: {m}\n    aggregation: mean\n    weight_by_size: true"
            for m in metrics
        )
        (here / f"linguasafe_{comp}.yaml").write_text(
            HEADER
            + f"group: linguasafe_{comp}\ntask:\n{tasks}\n"
            + f"aggregate_metric_list:\n{aggs}\nmetadata:\n  version: 1.0\n",
            encoding="utf-8",
        )
    tasks = "\n".join(f"  - linguasafe_{c}" for c in DEFAULT_GROUP)
    (here / "linguasafe.yaml").write_text(
        HEADER + f"group: linguasafe\ntask:\n{tasks}\nmetadata:\n  version: 1.0\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(COMPONENTS) * (len(LANGS) + 1) + 1} configs to {here}")


if __name__ == "__main__":
    main()
