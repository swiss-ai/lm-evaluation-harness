#!/usr/bin/env python3
"""Generate the PolyGuardPrompts task yamls.

- ``polyguardprompts_<lang>`` (17): the evaluated model answers the prompts,
  PolyGuard judges the responses. Group: ``polyguardprompts``.
- ``polyguardprompts_cls_<lang>`` (17): the evaluated model acts as the safety
  classifier (original use of the dataset). Group: ``polyguardprompts_cls``.

Run from anywhere: ``python generate_configs.py``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))

from metric import _GEN_METRICS, CLS_SYSTEM_PROMPT
from utils import LANGUAGES


HEADER = "# Generated by generate_configs.py; do not edit by hand.\n"

# Direction of each generation metric (lower harmful/over-refusal is better;
# more refusals of harmful prompts is better).
HIGHER_IS_BETTER = {m: False for m in _GEN_METRICS}
HIGHER_IS_BETTER["refusal_rate_harmful"] = True

CLS_METRICS = {
    "f1_harmful_request": ("metric.f1_agg", True),
    "f1_response_refusal": ("metric.f1_agg", True),
    "f1_harmful_response": ("metric.f1_agg", True),
    "parse_error_rate": ("mean", False),
}


def gen_template() -> str:
    lines = [
        HEADER.rstrip(),
        "dataset_path: ToxicityPrompts/PolyGuardPrompts",
        "output_type: generate_until",
        "test_split: test",
        'doc_to_text: "{{prompt}}"',
        'doc_to_target: ""',
        "process_results: !function metric.process_results_gen",
        "metric_list:",
    ]
    for m in _GEN_METRICS:
        lines += [
            f"  - metric: {m}",
            f"    aggregation: !function metric.{m}",
            f"    higher_is_better: {str(HIGHER_IS_BETTER[m]).lower()}",
        ]
    lines += [
        "generation_kwargs:",
        "  until: []",
        "  do_sample: false",
        "  temperature: 0.0",
        "  max_new_tokens: 512",
        "metadata:",
        "  version: 1.0",
    ]
    return "\n".join(lines) + "\n"


def cls_template() -> str:
    lines = [
        HEADER.rstrip(),
        "dataset_path: ToxicityPrompts/PolyGuardPrompts",
        "output_type: generate_until",
        "test_split: test",
        # json.dumps gives a valid double-quoted YAML scalar.
        f"description: {json.dumps(CLS_SYSTEM_PROMPT, ensure_ascii=False)}",
        "doc_to_text: !function metric.doc_to_text_cls",
        'doc_to_target: ""',
        "process_results: !function metric.process_results_cls",
        "metric_list:",
    ]
    for m, (agg, hib) in CLS_METRICS.items():
        agg_s = f"!function {agg}" if "." in agg else agg
        lines += [
            f"  - metric: {m}",
            f"    aggregation: {agg_s}",
            f"    higher_is_better: {str(hib).lower()}",
        ]
    lines += [
        "generation_kwargs:",
        "  until: []",
        "  do_sample: false",
        "  temperature: 0.0",
        "  max_new_tokens: 100",
        "metadata:",
        "  version: 1.0",
    ]
    return "\n".join(lines) + "\n"


def group(name: str, tasks: list[str], metrics: list[str]) -> str:
    lines = [HEADER.rstrip(), f"group: {name}", "task:"]
    lines += [f"  - {t}" for t in tasks]
    lines.append("aggregate_metric_list:")
    for m in metrics:
        lines += [
            f"  - metric: {m}",
            "    aggregation: mean",
            "    weight_by_size: true",
        ]
    lines += ["metadata:", "  version: 1.0"]
    return "\n".join(lines) + "\n"


def main():
    (HERE / "_polyguardprompts_yaml").write_text(gen_template(), encoding="utf-8")
    (HERE / "_polyguardprompts_cls_yaml").write_text(cls_template(), encoding="utf-8")
    gen_tasks, cls_tasks = [], []
    for code in LANGUAGES:
        t = f"polyguardprompts_{code}"
        (HERE / f"{t}.yaml").write_text(
            f"{HEADER}task: {t}\ninclude: _polyguardprompts_yaml\n"
            f"process_docs: !function utils.process_docs_{code}\n",
            encoding="utf-8",
        )
        gen_tasks.append(t)
        t = f"polyguardprompts_cls_{code}"
        (HERE / f"{t}.yaml").write_text(
            f"{HEADER}task: {t}\ninclude: _polyguardprompts_cls_yaml\n"
            f"process_docs: !function utils.process_docs_cls_{code}\n",
            encoding="utf-8",
        )
        cls_tasks.append(t)
    (HERE / "polyguardprompts.yaml").write_text(
        group("polyguardprompts", gen_tasks, _GEN_METRICS), encoding="utf-8"
    )
    (HERE / "polyguardprompts_cls.yaml").write_text(
        group("polyguardprompts_cls", cls_tasks, list(CLS_METRICS)), encoding="utf-8"
    )
    print(f"Wrote {len(gen_tasks)} + {len(cls_tasks)} task yamls and 2 groups.")


if __name__ == "__main__":
    main()
