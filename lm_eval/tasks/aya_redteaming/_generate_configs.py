"""Generate the Aya Red-teaming task configs.

Writes the shared template ``_aya_redteaming_yaml``, one ``aya_redteaming_<lang>.yaml``
per dataset split, and the group ``aya_redteaming.yaml``. Harm-category metric
names come from ``HARM_CATEGORIES`` in metric.py (read with ``ast`` so that this
script does not import metric.py, which needs the judge API).

Usage: python lm_eval/tasks/aya_redteaming/_generate_configs.py
"""

import ast
from pathlib import Path


HERE = Path(__file__).parent

# Dataset splits (CohereLabs/aya_redteaming, config "default"); 7,419 prompts total.
LANGUAGES = {
    "arabic": 900,
    "english": 987,
    "filipino": 1009,
    "french": 813,
    "hindi": 915,
    "russian": 1007,
    "serbian": 1006,
    "spanish": 782,
}


def _harm_category_slugs():
    tree = ast.parse((HERE / "metric.py").read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "HARM_CATEGORIES" for t in node.targets
        ):
            return list(ast.literal_eval(node.value))
    raise RuntimeError("HARM_CATEGORIES not found in metric.py")


def _metrics():
    """(metric name, aggregation function name, higher_is_better)."""
    rows = [
        ("score", "harmful_rate_agg", False),
        ("harmful_rate", "harmful_rate_agg", False),
        ("harmful_rate_global", "harmful_rate_global_agg", False),
        ("harmful_rate_local", "harmful_rate_local_agg", False),
    ]
    rows += [
        (f"harmful_rate_{s}", f"harmful_rate_{s}_agg", False)
        for s in _harm_category_slugs()
    ]
    rows.append(("judge_failure_rate", "judge_failure_rate_agg", False))
    return rows


HEADER = "# Generated by _generate_configs.py. Do not edit by hand.\n"


def write_template():
    lines = [
        HEADER.rstrip(),
        "dataset_path: CohereLabs/aya_redteaming",
        "dataset_name: default",
        "output_type: generate_until",
        "training_split: null",
        "test_split: english",
        "process_docs: !function metric.process_docs",
        'doc_to_text: "{{prompt}}"',
        'doc_to_target: ""',
        "process_results: !function metric.harmfulness_score",
        "# All rates are fractions of judged completions rated harmful: lower is better.",
        "metric_list:",
    ]
    for name, agg, hib in _metrics():
        lines += [
            f"  - metric: {name}",
            f"    aggregation: !function metric.{agg}",
            f"    higher_is_better: {str(hib).lower()}",
        ]
    lines += [
        "generation_kwargs:",
        "  do_sample: false",
        "  temperature: 0.0",
        "  max_new_tokens: 512",
        "  # No stop strings beyond EOS: the default (fewshot delimiter \"\\n\\n\")",
        "  # would cut responses at the first blank line.",
        "  until: []",
        "metadata:",
        "  version: 2.0",
        "",
    ]
    (HERE / "_aya_redteaming_yaml").write_text("\n".join(lines), encoding="utf-8")


def write_languages():
    for lang in LANGUAGES:
        (HERE / f"aya_redteaming_{lang}.yaml").write_text(
            HEADER
            + f"task: aya_redteaming_{lang}\n"
            + "include: _aya_redteaming_yaml\n"
            + f"test_split: {lang}\n",
            encoding="utf-8",
        )


def write_group():
    lines = [HEADER.rstrip(), "group: aya_redteaming", "task:"]
    lines += [f"  - aya_redteaming_{lang}" for lang in LANGUAGES]
    lines += [
        "# Size-weighted mean of the per-language values. For the subset metrics",
        "# (global/local, categories) this weights by language size, not subset size;",
        "# exact pooled numbers can be computed from the judge logs.",
        "aggregate_metric_list:",
    ]
    for name, _, _ in _metrics():
        lines += [
            f"  - metric: {name}",
            "    aggregation: mean",
            "    weight_by_size: true",
        ]
    lines += ["metadata:", "  version: 2.0", ""]
    (HERE / "aya_redteaming.yaml").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    write_template()
    write_languages()
    write_group()
    print(f"Wrote configs for {len(LANGUAGES)} languages, {len(_metrics())} metrics.")
