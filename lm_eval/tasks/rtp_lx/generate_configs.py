#!/usr/bin/env python3
"""Generate RTP-LX task configs.

Writes, next to this script:
  generation/rtp_lx_<loc>.yaml          (40 locales) + rtp_lx.yaml group
  classification/rtp_lx_judge_<loc>.yaml (40 locales) + rtp_lx_judge.yaml group
  _rtp_lx_judge_yaml                    (template; embeds the official prompt)
Run from this directory: python generate_configs.py
"""

import json
from pathlib import Path

from judge_prompt import SYSTEM_PROMPT


# Locale code (= file name in the data) -> language, as in RTP-LX v1.5.
LOCALES = {
    "AR": "Arabic (MSA + Egyptian/Levantine/Saudi dialect prompts)",
    "BCMS": "Bosnian/Croatian/Montenegrin/Serbian",
    "BG": "Bulgarian",
    "CA": "Catalan",
    "CS": "Czech",
    "CY": "Welsh",
    "DA": "Danish",
    "DE": "German (Germany)",
    "DE-CH": "German (Switzerland)",
    "EL": "Greek",
    "EN": "English (RTP source)",
    "ES": "Spanish (Spain)",
    "ET": "Estonian",
    "FI": "Finnish",
    "FR": "French (France)",
    "HE": "Hebrew",
    "HI": "Hindi",
    "HU": "Hungarian",
    "ID": "Indonesian",
    "IT": "Italian",
    "JA": "Japanese",
    "KO": "Korean",
    "LT": "Lithuanian",
    "LV": "Latvian",
    "NL": "Dutch",
    "NO-NB": "Norwegian (Bokmal)",
    "PL": "Polish",
    "PT": "Portuguese (Brazil + Portugal)",
    "RO": "Romanian",
    "RU": "Russian (Russia + Ukraine)",
    "SK": "Slovak",
    "SL": "Slovenian",
    "SV": "Swedish",
    "SW": "Swahili",
    "TH": "Thai",
    "TR": "Turkish",
    "UK": "Ukrainian",
    "VI": "Vietnamese",
    "ZH-Hans": "Chinese (Simplified)",
    "ZH-Hant": "Chinese (Traditional)",
}

CATEGORIES = [
    "toxicity",
    "identityattack",
    "bias",
    "microaggression",
    "violence",
    "selfharm",
    "insult",
    "sexualcontent",
]


def suffix(loc: str) -> str:
    return loc.lower().replace("-", "_")


def judge_template() -> str:
    metrics = [f"kappa_{c}" for c in CATEGORIES] + [
        "kappa_avg",
        "acc_avg",
        "acc_toxicity",
    ]
    lines = [
        "# RTP-LX classification task (paper setup): the model scores each prompt",
        "# on the 8 RTP-LX categories; compared with the human majority vote.",
        "# GENERATED by generate_configs.py -- edit there.",
        "dataset_path: json  # nominal; data comes from custom_dataset",
        "custom_dataset: !function utils.load_rtp_lx",
        "output_type: generate_until",
        "test_split: test",
        # json.dumps gives a valid YAML double-quoted scalar.
        f"description: {json.dumps(SYSTEM_PROMPT, ensure_ascii=False)}",
        'doc_to_text: "{{prompt}}"',
        'doc_to_target: ""',
        "process_results: !function judge_metric.process_results",
        "metric_list:",
    ]
    for m in metrics:
        lines += [
            f"  - metric: {m}",
            f"    aggregation: !function judge_metric.{m}",
            "    higher_is_better: true",
        ]
    lines += [
        "  - metric: parse_error",
        "    aggregation: mean",
        "    higher_is_better: false",
        "generation_kwargs:",
        "  until:",
        '    - "Text:"',
        "  do_sample: false",
        "  temperature: 0.0",
        "  max_gen_toks: 200",
        "metadata:",
        "  version: 1.0",
    ]
    return "\n".join(lines) + "\n"


def group(name, tasks, metrics) -> str:
    out = [f"group: {name}", "task:"] + [f"  - {t}" for t in tasks]
    out.append("aggregate_metric_list:")
    for m in metrics:
        out += [f"  - metric: {m}", "    aggregation: mean", "    weight_by_size: true"]
    out += ["metadata:", "  version: 1.0"]
    return "\n".join(out) + "\n"


def main():
    here = Path(__file__).parent
    gen, cls = here / "generation", here / "classification"
    gen.mkdir(exist_ok=True)
    cls.mkdir(exist_ok=True)

    # !function paths resolve relative to the file holding the tag, so the
    # templates sit next to the .py modules and subtasks include ../<template>.
    (here / "_rtp_lx_judge_yaml").write_text(judge_template(), encoding="utf-8")

    gen_tasks, cls_tasks = [], []
    for loc in LOCALES:
        s = suffix(loc)
        gen_tasks.append(f"rtp_lx_{s}")
        (gen / f"rtp_lx_{s}.yaml").write_text(
            f"task: rtp_lx_{s}\ninclude: ../_rtp_lx_yaml\n"
            f"dataset_kwargs:\n  locale: {loc}\n",
            encoding="utf-8",
        )
        cls_tasks.append(f"rtp_lx_judge_{s}")
        (cls / f"rtp_lx_judge_{s}.yaml").write_text(
            f"task: rtp_lx_judge_{s}\ninclude: ../_rtp_lx_judge_yaml\n"
            f"dataset_kwargs:\n  locale: {loc}\n",
            encoding="utf-8",
        )

    (here / "rtp_lx.yaml").write_text(
        group("rtp_lx", gen_tasks, ["unsafe", "judge_error"]), encoding="utf-8"
    )
    cls_metrics = [f"kappa_{c}" for c in CATEGORIES] + [
        "kappa_avg",
        "acc_avg",
        "acc_toxicity",
        "parse_error",
    ]
    (here / "rtp_lx_judge.yaml").write_text(
        group("rtp_lx_judge", cls_tasks, cls_metrics), encoding="utf-8"
    )
    print(
        f"wrote {len(gen_tasks)} generation + {len(cls_tasks)} classification configs"
    )


if __name__ == "__main__":
    main()
